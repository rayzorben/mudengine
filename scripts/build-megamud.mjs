/**
 * Takes what this client needs from MegaMUD's shipped tables, once (todo 817).
 *
 * Reads `mega-paramud/Default/MONSTERS.md` and `MESSAGES.md` through
 * `lib/megamud-db.mjs` and writes, in this client's own words:
 *
 * - `resources/megamud/monsters.yaml`: `mobRules` rows, the lowest scope of
 *   the monster list on every realm (a row for a monster a realm does not
 *   have never matches there);
 * - `resources/megamud/messages.csv`: each sentence MegaMUD knows a meaning
 *   for, the sentence that ends it, and what it means.
 *
 * Nothing at runtime reads MegaMUD's files, so the generated files are
 * committed and this is run again only to re-derive them.
 *
 *   npm run build:megamud [-- <mega-paramud/Default> <out dir>]
 */
import fs from 'node:fs';
import path from 'node:path';
import { stringify } from 'yaml';

import { mobKey } from '../src/shared/world.ts';
import { MESSAGE_FLAGS, MONSTER_FLAGS, readMessages, readMonsters } from './lib/megamud-db.mjs';

const source = process.argv[2] ?? path.resolve('mega-paramud/Default');
const out = process.argv[3] ?? path.resolve('resources/megamud');
if (!fs.existsSync(path.join(source, 'MONSTERS.md'))) {
  console.error(`build:megamud: no MegaMUD tables at ${source}; pass the Default directory`);
  process.exit(1);
}

/* ------------------------------------------------------------ monsters */

/*
 * Friend becomes `never`, and Not hostile is not carried: both would make a
 * monster no threat (`peaceOf`), and this table is Paramud's, laid on every
 * realm. `never` still leaves it alone and never hits it back; whether it is
 * a threat stays the realm data's, unless the player writes the row.
 */
const STANCES = { friend: 'never', avoid: 'never', escape: 'escape', hangup: 'hangup' };
const BANDS = [
  ['first', MONSTER_FLAGS.first],
  ['high', MONSTER_FLAGS.high],
  ['low', MONSTER_FLAGS.low],
  ['last', MONSTER_FLAGS.last]
];

/** A record's row, or null when it says nothing an unlisted monster would not. */
function rowOf(monster) {
  const mob = mobKey(monster.name);
  const stance = STANCES[monster.relationship];
  if (stance !== undefined) return { mob, treat: stance };
  const band = BANDS.find(([, bit]) => monster.flags & bit)?.[0];
  const row = { mob, treat: band ?? 'default' };
  if (monster.attack.spell.length > 0) row.cast = { ...monster.attack };
  if (monster.flags & MONSTER_FLAGS.noBackstab) row.noBackstab = true;
  if (monster.flags & MONSTER_FLAGS.stopToKill) row.stopToKill = true;
  return band === undefined && Object.keys(row).length === 2 ? null : row;
}

const monsters = readMonsters(fs.readFileSync(path.join(source, 'MONSTERS.md')));
const rows = new Map();
const disagree = new Set();
let nothing = 0;
for (const monster of monsters) {
  const row = rowOf(monster);
  if (row === null || row.mob.length === 0) {
    nothing += 1;
    continue;
  }
  const held = rows.get(row.mob);
  if (held === undefined) rows.set(row.mob, row);
  else if (JSON.stringify(held) !== JSON.stringify(row)) disagree.add(row.mob);
}
// A name whose records disagree is left out rather than one of them picked.
for (const mob of disagree) rows.delete(mob);
const kept = [...rows.values()].sort((a, b) => a.mob.localeCompare(b.mob));

/** Comment lines of at most 78 characters. */
function wrapped(text) {
  const out = [];
  let line = '#';
  for (const word of text.split(' ')) {
    if (line.length + word.length + 1 > 78) {
      out.push(line);
      line = '#';
    }
    line += ` ${word}`;
  }
  return [...out, line].join('\n');
}

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(
  path.join(out, 'monsters.yaml'),
  `# MegaMUD's monster table, as monster list rows.
#
# Generated by \`npm run build:megamud\` from mega-paramud/Default/MONSTERS.md,
# the table MegaMUD ships for Paramud. These rows sit beneath the monster list
# on every realm: a row in the options file, a realm or a character replaces
# the row here for the same monster, and a row for a monster a realm does not
# have never matches there.
#
# MegaMUD's Avoid and Friend are \`never\`, its Flee \`escape\`; its priorities
# are the bands; Don't backstab carries over. Friend and Not hostile would make
# a monster no threat on every realm, whatever that realm's data says, so
# neither is carried: a \`friend\` or Not hostile row is the player's to write.
# Enemy at Normal priority is what an unlisted monster already gets, so those
# records are left out.
#
# ${kept.length} rows from ${monsters.length} records.
# Left out: ${nothing} that say nothing beyond an unlisted monster, and
# ${disagree.size} names whose records disagree:
${wrapped([...disagree].sort().join(', ') + '.')}
${stringify({ mobRules: kept }, { lineWidth: 0 })}`
);

/* ------------------------------------------------------------ messages */

const CONDITIONS = [
  'blind',
  'confused',
  'poisoned',
  'diseased',
  'held',
  'attack-prevented',
  'losing-hp',
  'hp-regen',
  'mana-regen'
];
const MEANINGS = ['ends-combat', 'action-failed'];
const words = (flags, names) => names.filter((name) => flags & MESSAGE_FLAGS[name]).join('|');
const cell = (value) => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);

const records = readMessages(fs.readFileSync(path.join(source, 'MESSAGES.md'), 'latin1'));
const live = records.filter((record) => !(record.flags & MESSAGE_FLAGS.disabled));
const said = live.filter((record) => record.start.length > 0);
const lines = said.map((record) => {
  const chasing = (record.flags & MESSAGE_FLAGS.chasing) !== 0;
  return [
    record.name,
    record.start,
    record.stop,
    words(record.flags, CONDITIONS),
    words(record.flags, MEANINGS),
    record.action === 'none' ? '' : record.action,
    chasing ? '' : record.response,
    chasing ? record.response : '',
    record.flags & MESSAGE_FLAGS.conversations ? 'yes' : ''
  ]
    .map(cell)
    .join(',');
});
fs.writeFileSync(
  path.join(out, 'messages.csv'),
  `${['name', 'start', 'stop', 'conditions', 'meaning', 'action', 'response', 'chase', 'conversations'].join(',')}\n${lines.join('\n')}\n`,
  'latin1'
);

console.log(
  `build:megamud: ${kept.length} monster rows (${nothing} say nothing, ${disagree.size} names disagree); ` +
    `${said.length} messages (${records.length - live.length} disabled, ${live.length - said.length} empty)`
);
